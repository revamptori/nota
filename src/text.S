/*
 * text.S - glyph lookup, UTF-8 decoding and text measurement.
 *
 * The font is a dense two-run index (ASCII, then Latin-1) plus a small sorted
 * table of strays, so lookup for real text is two subtracts and a compare and
 * only currency symbols and curly quotes pay for a scan.
 *
 * Everything here works in UTF-8 byte offsets, matching the editor: a caller
 * passes a pointer and a length and gets back advances or caret positions.
 */
#include "nota.h"

    .equ ASCII_FIRST, 0x20
    .equ ASCII_LAST,  0x7E
    .equ LATIN_FIRST, 0xA0
    .equ LATIN_LAST,  0xFF
    .equ ASCII_BASE,  0      /* glyph index of U+0020 */
    .equ LATIN_BASE,  95     /* glyph index of U+00A0 */
    .equ STRAY_BASE,  191

    /* font.S is generated by tools/mkfont.py; these are the fields it emits. */
    .equ FM_W,        0      /* atlas pixel width   */
    .equ FM_H,        4      /* atlas pixel height  */
    .equ FM_CELLW,    8
    .equ FM_CELLH,    12
    .equ FM_BASELINE, 16
    .equ FM_COUNT,    20
    .equ FM_ASCII0,   24

/* ========================================================================= *
 * long nota_glyph(u32 cp) - glyph index for a code point, or -1.
 * ========================================================================= */
    .globl nota_glyph
    .type  nota_glyph, %function
nota_glyph:
    mov    w9, #ASCII_FIRST
    sub    w10, w0, w9
    cmp    w10, #(ASCII_LAST - ASCII_FIRST)
    b.hi   .Lgl_latin
    mov    w0, w10
    ret
.Lgl_latin:
    mov    w9, #LATIN_FIRST
    sub    w10, w0, w9
    cmp    w10, #(LATIN_LAST - LATIN_FIRST)
    b.hi   .Lgl_stray
    add    w0, w10, #LATIN_BASE
    ret
.Lgl_stray:
    adrp   x9, nota_font_strays
    add    x9, x9, :lo12:nota_font_strays
    ldrb   w10, [x9]            /* entry count */
    cbz    w10, .Lgl_none
    /* One count byte, then 4-byte entries: u16 code point, u16 glyph index.
       The entries therefore start at +1, not +2 - skipping two bytes starts
       the scan half a code point in, so the first entry is never found and
       the sorted-order test rejects the rest. */
    add    x9, x9, #1
    /* Deliberately a linear scan: there are nine strays and a binary search
       would cost more in setup than it saves. */
.Lgl_scan:
    ldrh   w11, [x9]
    cmp    w11, w0
    b.eq   .Lgl_hit
    b.hi   .Lgl_none            /* sorted, so a bigger code point ends it */
    add    x9, x9, #4
    subs   w10, w10, #1
    b.ne   .Lgl_scan
.Lgl_none:
    mov    x0, #-1
    ret
.Lgl_hit:
    ldrh   w0, [x9, #2]
    ret
    .size nota_glyph, . - nota_glyph

/* ========================================================================= *
 * long nota_glyph_advance(long idx) - advance width in pixels, or 0.
 * ========================================================================= */
    .globl nota_glyph_advance
    .type  nota_glyph_advance, %function
nota_glyph_advance:
    tbnz   x0, #63, .Lga_zero
    adrp   x9, nota_font_meta
    add    x9, x9, :lo12:nota_font_meta
    ldr    w10, [x9, #FM_COUNT]
    cmp    x0, x10
    b.hs   .Lga_zero
    adrp   x9, nota_font_adv
    add    x9, x9, :lo12:nota_font_adv
    ldrb   w0, [x9, x0]
    ret
.Lga_zero:
    mov    x0, #0
    ret
    .size nota_glyph_advance, . - nota_glyph_advance

/* ========================================================================= *
 * long nota_text_width(const char *s, long len)
 * Pixel advance of a UTF-8 string, ignoring the tail of a cut code point
 * (which is what a partially scrolled line looks like).
 * ========================================================================= */
    .globl nota_text_width
    .type  nota_text_width, %function
nota_text_width:
    stp    x29, x30, [sp, #-64]!
    mov    x29, sp
    stp    x19, x20, [sp, #16]
    stp    x21, x22, [sp, #32]
    mov    x19, x0
    add    x20, x0, x1          /* end */
    mov    x21, #0              /* total */
.Ltw_loop:
    cmp    x19, x20
    b.hs   .Ltw_done
    mov    x0, x19
    add    x1, sp, #80
    bl     nota_utf8_decode     /* x0 = bytes consumed, cp written to x1 */
    cbz    x0, .Ltw_done        /* NUL: end of text */
    mov    x22, x0
    add    x19, x19, x22
    ldr    w0, [sp, #80]
    bl     nota_glyph
    bl     nota_glyph_advance
    add    x21, x21, x0
    b      .Ltw_loop
.Ltw_done:
    mov    x0, x21
    ldp    x21, x22, [sp, #32]
    ldp    x19, x20, [sp, #16]
    ldp    x29, x30, [sp], #64
    ret
    .size nota_text_width, . - nota_text_width

/* ========================================================================= *
 * long nota_text_emit(const char *s, long len, long x, long y, long maxx)
 * Draws a UTF-8 string with its baseline at y, returning the final pen x.
 * Anything that would cross maxx is skipped rather than clipped by the
 * scissor, keeping the vertex budget for things that are actually visible.
 * ========================================================================= */
    .globl nota_text_emit
    .type  nota_text_emit, %function
nota_text_emit:
    /* frame: x29/x30 at 0, x19-x26 at 16..80, scratch code point at 80.
       The scratch slot used to be at 76, in the top half of the saved x26
       pair, so decoding a character quietly rewrote the saved byte length and
       the loop then walked off the end of the string. */
    stp    x29, x30, [sp, #-96]!
    mov    x29, sp
    stp    x19, x20, [sp, #16]
    stp    x21, x22, [sp, #32]
    stp    x23, x24, [sp, #48]
    stp    x25, x26, [sp, #64]
    mov    x19, x0              /* s     */
    add    x20, x0, x1          /* end   */
    mov    x21, x2              /* pen x */
    mov    x22, x3              /* baseline y */
    mov    x23, x4              /* max x */
    adrp   x9, nota_font_meta
    add    x9, x9, :lo12:nota_font_meta
    ldr    w24, [x9, #FM_CELLW] /* atlas cell size */
    ldr    w25, [x9, #FM_CELLH]
.Lte_loop:
    cmp    x19, x20
    b.hs   .Lte_done
    cmp    x21, x23
    b.hs   .Lte_done
    mov    x0, x19
    add    x1, sp, #80
    bl     nota_utf8_decode
    cbz    x0, .Lte_done
    mov    x26, x0              /* bytes consumed */
    ldr    w0, [sp, #80]
    bl     nota_glyph
    tbnz   x0, #63, .Lte_skip   /* no glyph: advance nothing, show nothing */
    /* The glyph index has to survive nota_gl_quad, which uses x10 for the
       vertex count. Leaving it in a caller-saved register looked up the
       advance of an arbitrary glyph - usually glyph 0, whose advance is 0, so
       every character after the first landed on the same pen position. */
    str    x0, [sp, #88]        /* glyph index */
    ldr    w10, [sp, #88]
    /* atlas cell -> pixel rectangle, flipped to v-at-top ordering */
    mov    w11, #13             /* atlas columns, from mkfont.py */
    udiv   w12, w10, w11
    msub   w13, w12, w11, w10   /* column */
    mul    w12, w12, w25        /* v0 = row * cell_h */
    madd   w14, w13, w24, wzr   /* u0 = col * cell_w */
    add    w15, w14, w24        /* u1 */
    add    w16, w12, w25        /* v1 */

    /* dest rect: pen x, top = baseline - baseline_offset, height = cell_h */
    mov    x0, x21
    adrp   x9, nota_font_meta
    add    x9, x9, :lo12:nota_font_meta
    ldr    w17, [x9, #FM_BASELINE]
    sub    x1, x22, x17
    add    x2, x21, x24
    add    x3, x1, x25
    mov    x4, x14
    mov    x5, x12
    mov    x6, x15
    mov    x7, x16
    bl     nota_gl_quad

    ldr    x0, [sp, #88]        /* the index, not whatever quad left in x10 */
    bl     nota_glyph_advance
    add    x21, x21, x0
.Lte_skip:
    add    x19, x19, x26
    b      .Lte_loop
.Lte_done:
    mov    x0, x21
    ldp    x25, x26, [sp, #64]
    ldp    x23, x24, [sp, #48]
    ldp    x21, x22, [sp, #32]
    ldp    x19, x20, [sp, #16]
    ldp    x29, x30, [sp], #96
    ret
    .size nota_text_emit, . - nota_text_emit


/* ========================================================================= *
 * long nota_ui_text(const char *s, long len, long x, long baseline, u32 rgba)
 * Set colour and draw. Returns the pen x after the last glyph.
 * ========================================================================= */
    .globl nota_ui_text
    .type  nota_ui_text, %function
nota_ui_text:
    stp    x29, x30, [sp, #-64]!
    mov    x29, sp
    stp    x19, x20, [sp, #16]
    stp    x21, x22, [sp, #32]
    stp    x23, x24, [sp, #48]
    mov    x19, x0              /* s */
    mov    x20, x1              /* len */
    mov    x21, x2              /* x */
    mov    x22, x3              /* baseline */
    mov    w23, w4              /* colour */
    mov    w0, w23
    bl     nota_gl_color0
    /* max x: the far edge, so nothing is skipped unless the caller clips */
    mov    x4, #0x7FFFFFFFFFFFFFFF
    mov    x0, x19
    mov    x1, x20
    mov    x2, x21
    mov    x3, x22
    adrp   x9, nota_ui
    add    x9, x9, :lo12:nota_ui
    ldr    x4, [x9]
    mov    x9, #1
    lsl    x9, x9, #62          /* effectively unbounded */
    bl     nota_text_emit
    ldp    x23, x24, [sp, #48]
    ldp    x21, x22, [sp, #32]
    ldp    x19, x20, [sp, #16]
    ldp    x29, x30, [sp], #64
    ret
    .size nota_ui_text, . - nota_ui_text

/* ========================================================================= *
 * long nota_ui_text_clip(const char *s, long len, long x, long baseline,
 *                        u32 rgba, long maxx)
 * Colour, then draw stopping at maxx.
 * ========================================================================= */
    .globl nota_ui_text_clip
    .type  nota_ui_text_clip, %function
nota_ui_text_clip:
    stp    x29, x30, [sp, #-64]!
    mov    x29, sp
    stp    x19, x20, [sp, #16]
    stp    x21, x22, [sp, #32]
    str    x23, [sp, #48]
    mov    x19, x0
    mov    x20, x1
    mov    x21, x2
    mov    x22, x3
    mov    w0, w4
    bl     nota_gl_color0
    mov    x23, x5
    mov    x0, x19
    mov    x1, x20
    mov    x2, x21
    mov    x3, x22
    mov    x4, x23
    bl     nota_text_emit
    ldr    x23, [sp, #48]
    ldp    x21, x22, [sp, #32]
    ldp    x19, x20, [sp, #16]
    ldp    x29, x30, [sp], #64
    ret
    .size nota_ui_text_clip, . - nota_ui_text_clip


/* ========================================================================= *
 * long nota_edit_offset_at_x(const char *s, long len, long x)
 * Byte offset in s nearest to pixel x: the position whose pen would be
 * closest to the tap. Tapping the right half of a glyph puts the caret after
 * it, which is what a text editor is expected to do.
 * ========================================================================= */
    .globl nota_edit_offset_at_x
    .type  nota_edit_offset_at_x, %function
nota_edit_offset_at_x:
    stp    x29, x30, [sp, #-96]!
    mov    x29, sp
    stp    x19, x20, [sp, #16]
    stp    x21, x22, [sp, #32]
    stp    x23, x24, [sp, #48]
    str    x25, [sp, #64]
    mov    x19, x0              /* s   */
    add    x20, x0, x1          /* end */
    mov    x21, x2              /* target x */
    cmp    x21, #0
    b.gt   1f
    mov    x0, #0
    b      .Leoa_ret
1:  mov    x22, x19             /* pen cursor */
    mov    x23, #0              /* advance so far */
    mov    x24, #0              /* best byte offset */
.Leoa_loop:
    cmp    x22, x20
    b.hs   .Leoa_done
    ldrb   w9, [x22]
    cmp    w9, #10
    b.eq   .Leoa_done
    mov    x0, x22
    add    x1, sp, #88
    bl     nota_utf8_decode
    cbz    x0, .Leoa_done
    mov    x25, x0
    ldr    w0, [sp, #88]
    bl     nota_glyph
    bl     nota_glyph_advance
    mov    x9, x0               /* advance of this glyph */
    /* midpoint test: is the tap past the middle of this glyph? */
    add    x10, x23, x9, lsr #1
    cmp    x21, x10
    b.lo   .Leoa_done           /* caret goes before this glyph */
    add    x23, x23, x9
    add    x22, x22, x25
    sub    x24, x22, x19
    cmp    x23, x21
    b.lo   .Leoa_loop
.Leoa_done:
    mov    x0, x24
.Leoa_ret:
    ldr    x25, [sp, #64]
    ldp    x23, x24, [sp, #48]
    ldp    x21, x22, [sp, #32]
    ldp    x19, x20, [sp, #16]
    ldp    x29, x30, [sp], #96
    ret
    .size nota_edit_offset_at_x, . - nota_edit_offset_at_x

