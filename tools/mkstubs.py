"""mkstubs.py - generate link-time stub shared objects for NDK libraries.

Build tooling only. When the real NDK is present (CI), linking uses the NDK's
libandroid.so/libEGL.so/libGLESv2.so/liblog.so. In environments without the
NDK (and for host unit tests) these stubs provide the same symbol names so the
linker can resolve references and record DT_NEEDED entries. A stub is never
packaged: it only satisfies the linker. The symbols emitted here are exactly the
ones NOTA imports, extracted from the sources so the list cannot drift.
"""
