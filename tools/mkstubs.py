STUB_TEMPLATE = """/* generated by tools/mkstubs.py - link-time stubs, never packaged */
.text
.macro NOTA_STUB name
.globl \\name
.type \\name, %function
\\name:
    ret
.endm
"""


def gen(lib, syms, cc):
    """Compile a stub .so exporting `syms`."""
    name = lib[:-3]
    src = STUB_TEMPLATE
    for s in syms:
        src += f"NOTA_STUB {s}\n"
    src += '.section .note.GNU-stack,"",%progbits\n'
    s_path = f"/tmp/{name}_stub.S"
    with open(s_path, "w") as fh:
        fh.write(src)
    return cc + ["-shared", "-nostdlib", "-fPIC", "-Wl,-soname," + lib,
                 "-Wl,--build-id=none", "-o", lib, s_path]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--cc", default=os.environ.get(
        "NOTA_CC", "zig cc -target aarch64-linux-android"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    cc = a.cc.split()
    for lib, syms in LIBS.items():
        syms = [s for s in syms if not s.endswith("_")]
        cmd = gen(lib, syms, cc)
        subprocess.run(cmd, check=True, cwd=a.out)
        print(f"  stub {lib} ({len(syms)} symbols)")


if __name__ == "__main__":
    main()
