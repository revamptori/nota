#!/usr/bin/env python3
"""mkfont.py - bake a text font into an assembly source file.

The app cannot read a system font at runtime (no FreeType, no libc), and
shipping a .ttf would mean writing a TrueType rasterizer in assembly. So the
glyphs are rasterized here, once, at build time, and emitted as a plain
alpha atlas plus a per-glyph advance table. The result is a `.S` file with no
dependencies: `src/font.S` is generated but committed, so a build never needs
Pillow or a font installed.

Atlas format (must match src/tex.S / src/ui.S):
    nota_font_meta:  .byte cell_h, baseline, first_ascii, glyph_count
                     .byte atlas_cols, atlas_rows, cell_w, 0
    nota_font_adv:   glyph_count bytes, advance width per glyph
    nota_font_atlas: atlas_cols*cell_w x atlas_rows*cell_h, 8-bit alpha,
                     row-major, each glyph in its own cell

Glyph index space is two dense runs plus a small sorted table of strays:
    0   .. 94   U+0020 .. U+007E   (ASCII, printable)
    95  .. 190  U+00A0 .. U+00FF   (Latin-1: accented letters, ß, ×, ÷)
    191 .. 199  the strays below (currency and typographic punctuation)

Dense indexing keeps lookup to two subtracts for the overwhelming majority of
text; only the strays need a scan.

Usage:  python3 tools/mkfont.py [-o src/font.S] [--ttf PATH] [--size N]
"""
import argparse
import os

# Stragglers that a notes app actually sees: the euro, curly quotes, dashes,
# ellipsis, bullet. Sorted by code point so the lookup table can be scanned.
STRAYS = sorted([0x20AC, 0x2018, 0x2019, 0x201C, 0x201D, 0x2013, 0x2014,
                 0x2026, 0x2022])

ASCII_FIRST, ASCII_LAST = 0x20, 0x7E
LATIN_FIRST, LATIN_LAST = 0xA0, 0xFF

CELL_W = 16
CELL_H = 20
BASELINE = 15          # pixels from the top of a cell to the baseline
COLS = 13              # 13 * 16 = 208 cells >= 200 glyphs
ROWS = 16
# Cell 200 is painted solid white and never used by a glyph: it is the texel
# solid quads sample, so text and chrome share one texture and one draw call.
WHITE_CELL = 200
WHITE_U = ((WHITE_CELL % COLS) * CELL_W + CELL_W / 2) / (COLS * CELL_W)
WHITE_V = ((WHITE_CELL // COLS) * CELL_H + CELL_H / 2) / (ROWS * CELL_H)

DEFAULT_TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def glyph_set():
    """(glyph index, code point) in index order."""
    out = []
    for cp in range(ASCII_FIRST, ASCII_LAST + 1):
        out.append(cp)
    for cp in range(LATIN_FIRST, LATIN_LAST + 1):
        out.append(cp)
    out.extend(STRAYS)
    return out


def render(ttf, size):
    from PIL import Image, ImageDraw, ImageFont

    cps = glyph_set()
    font = ImageFont.truetype(ttf, size)
    # Pillow's default anchor puts (0, 0) at the ascender top; we want the
    # glyph baseline at BASELINE so descenders get the room below it.
    atlas = Image.new("L", (COLS * CELL_W, ROWS * CELL_H), 0)
    draw = ImageDraw.Draw(atlas)
    adv = []
    for i, cp in enumerate(cps):
        ch = chr(cp)
        col, row = i % COLS, i // COLS
        x, y = col * CELL_W, row * CELL_H + BASELINE
        draw.text((x, y), ch, fill=255, font=font, anchor="ls")
        w = font.getlength(ch)
        # Round up but never below 2px: a zero advance would let a caret sit
        # on top of the previous glyph.
        adv.append(max(2, min(CELL_W, int(w + 0.5))))
    # the white cell
    wc = Image.new("L", (CELL_W, CELL_H), 255)
    atlas.paste(wc, ((WHITE_CELL % COLS) * CELL_W,
                     (WHITE_CELL // COLS) * CELL_H))
    return atlas, adv, cps


def emit(out_path, atlas, adv, cps):
    px = atlas.tobytes()
    assert len(px) == COLS * CELL_W * ROWS * CELL_H

    strays = [(cp, i) for i, cp in enumerate(cps) if cp > 0xFF]
    lines = []
    A = lines.append
    A("/* Generated by tools/mkfont.py - do not edit by hand.")
    A(" * %d glyphs, cell %dx%d, baseline %d, atlas %dx%d px." %
      (len(cps), CELL_W, CELL_H, BASELINE, COLS * CELL_W, ROWS * CELL_H))
    A(" */")
    A("#include \"nota.h\"")
    A("")
    A("    .section .rodata")
    A("    .p2align 4")
    A("")
    A("    .globl nota_font_meta")
    A("    .hidden nota_font_meta")
    A("    .type  nota_font_meta, %object")
    A("nota_font_meta:")
    A("    .word %d, %d, %d, %d" %
      (COLS * CELL_W, ROWS * CELL_H, CELL_W, CELL_H))
    A("    .word %d, %d, %d, 0" % (BASELINE, len(cps), ASCII_FIRST))
    A("    .size nota_font_meta, . - nota_font_meta")
    A("")
    A("/* Texel centre of the fully-white cell, so solid quads can share the")
    A(" * atlas instead of needing a second texture. */")
    A("    .globl nota_font_white")
    A("    .hidden nota_font_white")
    A("    .type  nota_font_white, %object")
    A("    .p2align 3")
    A("nota_font_white:")
    A("    .float %.8f, %.8f" % (WHITE_U, WHITE_V))
    A("    .size nota_font_white, . - nota_font_white")
    A("")
    A("/* u16 code point, u8 glyph index - scanned linearly, there are few. */")
    A("    .globl nota_font_strays")
    A("    .hidden nota_font_strays")
    A("    .type  nota_font_strays, %object")
    A("    .p2align 3")
    A("nota_font_strays:")
    A("    .byte %d" % len(strays))
    for cp, idx in strays:
        A("    .hword 0x%04X, %d" % (cp, idx))
    A("    .size nota_font_strays, . - nota_font_strays")
    A("")
    A("    .globl nota_font_adv")
    A("    .hidden nota_font_adv")
    A("    .type  nota_font_adv, %object")
    A("nota_font_adv:")
    for i in range(0, len(adv), 16):
        A("    .byte " + ", ".join(str(v) for v in adv[i:i + 16]))
    A("    .size nota_font_adv, . - nota_font_adv")
    A("")
    A("    .globl nota_font_atlas")
    A("    .hidden nota_font_atlas")
    A("    .type  nota_font_atlas, %object")
    A("nota_font_atlas:")
    for i in range(0, len(px), 32):
        A("    .byte " + ", ".join(str(v) for v in px[i:i + 32]))
    A("    .size nota_font_atlas, . - nota_font_atlas")
    A("")
    A("    .section .note.GNU-stack,\"\",%progbits")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return len(cps), len(px)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="src/font.S")
    ap.add_argument("--ttf", default=DEFAULT_TTF)
    ap.add_argument("--size", type=int, default=CELL_H - 5)
    a = ap.parse_args()
    if not os.path.exists(a.ttf):
        raise SystemExit("font not found: %s (pass --ttf)" % a.ttf)
    atlas, adv, cps = render(a.ttf, a.size)
    n, nbytes = emit(a.out, atlas, adv, cps)
    print("%s: %d glyphs, %d bytes of alpha" % (a.out, n, nbytes))


if __name__ == "__main__":
    main()
